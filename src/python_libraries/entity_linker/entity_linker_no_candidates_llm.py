import re

from .entity_linker_llm import EntityLinkerLLM
from ..llm_queries import LLMQueryHelper
from ..sentence_ner import Sentence
from ..snomed import Snomed, SnomedEmbedder

# Similarity from which the generated name is considered an exact match of a synonym in the search space.
# Cosine similarity between identical strings is 1.0, but it can be slightly lower due to floating-point rounding.
STRICT_MATCH_THRESHOLD = 0.9999

class EntityLinkerNoCandidatesLLM(EntityLinkerLLM):
    """Entity Linker subclass used as a control condition without a candidate list. After the (optional) abbreviation
    disambiguation, the LLM is asked to generate the name of the SNOMED CT concept for the span, using its context.
    The generated name is then mapped to the most similar synonym in the search space using the bi-encoder.

    The label of each entity is the concept of the most similar synonym (relaxed evaluation). The following information
    is stored in entity.other, always in the same order:
        - disabbrevation: span after abbreviation disambiguation (None if disabled).
        - new_context: sentence with the disambiguated span (None if replace_span is disabled).
        - context: original sentence.
        - hierarchy: SNOMED CT hierarchy used to restrict the search (None for the Spanish datasets).
        - llm_generated_name: name generated by the LLM (None if there was an error).
        - matched_name: most similar synonym in the search space.
        - matched_similarity: cosine similarity between the generated name and the matched synonym.
        - valid_concept: whether the generated name exactly matches a synonym (similarity >= strict_threshold), used for the strict evaluation.

    Attributes:
        ner_type2hierarchy (dict[str, str]):
            Dictionary to map the NER type assigned to the Entity to the concept type assigned in the SnomedEmbedder.
        strict_threshold (float):
            Similarity from which the generated name is considered an exact match of a synonym.
    """
    def __init__(self, snomed : Snomed, snomed_embedder : SnomedEmbedder, llm_query : LLMQueryHelper,
                 disambiguate_abbreviations : bool = True, replace_span : bool = True,
                 ner_type2hierarchy : dict[str, str] = None, spanish_version : bool = False,
                 strict_threshold : float = STRICT_MATCH_THRESHOLD):
        """Initializes the attributes of the class.

        Parameters:
            snomed (Snomed):
                Snomed object that contains information about the terminology.
            snomed_embedder (SnomedEmbedder):
                SnomedEmbedder object that uses embeddings for SNOMED CT.
            llm_query (LLMQueryHelper):
                LLMQueryHelper object that helps perform the queries to the LLMs.
            disambiguate_abbreviations (bool):
                Whether or not to disambiguate the abbreviations spans found.
            replace_span (bool):
                Whether to replace the disambiguated span in the original sentence text for the LLM. Defaults to True.
            ner_type2hierarchy (dict[str, str]):
                Dictionary to map the NER type assigned to the Entity to the concept type assigned in the SnomedEmbedder.
                Only used for the English version. If None, the search is not restricted to a hierarchy.
            spanish_version (bool):
                Whether to use the Spanish version of the prompts. Otherwise, it uses the English prompts. Defaults to False.
            strict_threshold (float):
                Similarity from which the generated name is considered an exact match of a synonym. Defaults to 0.9999.
        """
        super().__init__(snomed=snomed, snomed_embedder=snomed_embedder, llm_query=llm_query,
                         disambiguate_abbreviations=disambiguate_abbreviations, llm_for_el=True, rephrase=False,
                         replace_span=replace_span, use_fsn=False, threshold=None, spanish_version=spanish_version)
        self.ner_type2hierarchy = ner_type2hierarchy
        self.strict_threshold = strict_threshold

    def link_entities_from_sentence(self, sentence : Sentence):
        """Method that generates the name of the concept for each Entity in the Sentence with the LLM and maps it to the most
        similar concept in the search space. The concepts are assigned to the Entities.

        Parameters:
            sentence (Sentence):
                Sentence object that contains the entities to be linked, as well as additional information about the sentence.
        """
        section = sentence.section
        sentence_text = sentence.text

        for entity in sentence.entities:
            # Fresh dictionary so that every entity stores the same keys in the same order
            entity.other = dict(entity.other)
            span = entity.text

            # Abbreviation disambiguation, as in the full pipeline
            if self.disambiguate_abbreviations:
                new_span = self._resolve_disambiguation(sentence_text, span, section)
            else:
                new_span = span
            entity.other['disabbrevation'] = new_span if self.disambiguate_abbreviations else None

            if self.replace_span:
                new_sentence_text = sentence_text[:entity.start] + new_span + sentence_text[entity.end:]
            else:
                new_sentence_text = sentence_text
            entity.other['new_context'] = new_sentence_text if self.replace_span else None
            entity.other['context'] = sentence_text

            hierarchy = self._get_hierarchy(entity)
            entity.other['hierarchy'] = hierarchy

            # The LLM generates the name of the concept, without candidates
            generated_name = self._generate_concept_name(new_sentence_text, new_span, section)
            entity.other['llm_generated_name'] = generated_name

            if generated_name is None:
                entity.other['matched_name'] = None
                entity.other['matched_similarity'] = None
                entity.other['valid_concept'] = False
                entity.set_options([])
                entity.set_confidence(0.0)
                entity.set_label(-1)
                continue

            # Map the generated name to the most similar synonym in the search space
            sct_id, similarity, matched_name = self.snomed_embedder.get_most_similar_concept(generated_name, n=1, concept_type=hierarchy)[0]
            similarity = float(similarity)

            entity.other['matched_name'] = matched_name
            entity.other['matched_similarity'] = similarity
            entity.other['valid_concept'] = similarity >= self.strict_threshold
            entity.set_options([sct_id])
            entity.set_confidence(similarity)
            entity.set_label(sct_id)

    def _get_hierarchy(self, entity) -> str | None:
        """Returns the hierarchy used to restrict the search, following the same criteria as the full pipeline."""
        if self.spanish_version or self.ner_type2hierarchy is None:
            return None
        return self.ner_type2hierarchy[entity.ner_type]

    def _generate_concept_name(self, sentence_text : str, span : str, section : str) -> str | None:
        """Method used to ask the LLM for the name of the SNOMED CT concept that corresponds to the span.

        Parameters:
            sentence_text (str):
                String that represents the sentence that serves as context for the span.
            span (str):
                String that represents the span for which we want to identify the concept from SNOMED CT.
            section (str):
                String that represents the section from the text where the span was found.

        Returns:
            The name generated by the LLM, or None if there was an error or the response was empty.
        """
        if self.spanish_version:
            response = self.llm_query.send_request_EL_NC_es(sentence=sentence_text, span=span)
        else:
            response = self.llm_query.send_request_EL_NC(sentence=sentence_text, span=span, section=section)

        if response is None:
            return None

        name = response.strip()

        # Remove surrounding quotes, if any
        match = re.fullmatch(r'["\'`](.*)["\'`]', name, flags=re.DOTALL)
        if match is not None:
            name = match.group(1).strip()

        return name if name else None
